import type { CapacitorConfig } from "@capacitor/cli";

/**
 * Адрес сервиса, который открывает приложение.
 *
 * Переопределяется переменной, чтобы собрать сборку на другой сервер, не правя
 * файл: тем же способом, что и у десктопной обёртки.
 */
const SERVER = process.env.BADYUM_SERVER_URL ?? "https://badyum.ru";

/**
 * Android-обёртка над сайтом.
 *
 * Ключевое решение здесь — `server.url`: WebView грузит badyum.ru напрямую, а не
 * копию сайта, упакованную в APK. Причин две, и обе существенные.
 *
 * Первая — вход. Сессионная кука выдана с `SameSite=Lax`, и на запросы с чужого
 * origin браузер её не отправляет. Упакуй мы страницу в APK, она открывалась бы
 * как `https://localhost`, все обращения к API стали бы межсайтовыми, и вход
 * через Google в приложении просто не работал бы. Загружая сайт с его
 * собственного адреса, мы остаёмся в том же origin — куки, вход и WebSocket
 * ведут себя ровно как в браузере.
 *
 * Вторая — обновления. Приложение раздаётся файлом, а не через магазин, и
 * заставлять человека переустанавливать APK ради правки в интерфейсе никуда не
 * годится. Нативная часть тут — только фоновый сервис, меняется она редко;
 * всё остальное приезжает с сервера само.
 *
 * Мост Capacitor при этом никуда не девается. Он вшивается в главный документ:
 * запрос HTML-страницы перехватывается, и в поток ответа подмешивается
 * `native-bridge.js` вместе с кодом плагинов. Перехват касается только самого
 * документа — запросы к API, WebSocket и медиа идут мимо и ничего не теряют,
 * а куки переносятся в обе стороны через системный CookieManager.
 */
const config: CapacitorConfig = {
  appId: "app.badyum.mobile",
  appName: "Badyum",

  /**
   * Локальные файлы. При `server.url` сайт берётся с сервера, и сюда WebView не
   * заглядывает — кроме случая, когда сервер недоступен: тогда показывается
   * `offline.html` вместо системной ошибки «net::ERR_INTERNET_DISCONNECTED».
   */
  webDir: "public",

  server: {
    url: SERVER,
    // Только https. Разрешать открытый http значит позволить подменить
    // страницу приложения любому, кто оказался между телефоном и сервером.
    cleartext: false,
    errorPath: "offline.html",
  },

  android: {
    /**
     * Микрофон в WebView.
     *
     * Без этого getUserMedia в Android WebView отклоняется молча: WebView не
     * спрашивает разрешение сам, он перекладывает решение на приложение.
     * Capacitor отвечает согласием, если у самого приложения право есть, —
     * а его мы запрашиваем в VoicePlugin перед стартом сервиса.
     */
    allowMixedContent: false,
  },
};

export default config;
