-- Журнал клиентских поломок.
--
-- Все настоящие ошибки этого проекта нашлись не типами и не тестами, а тем,
-- что кто-то открыл два браузера и попробовал. С телефона в чужой сети такого
-- браузера у нас нет — эта таблица и есть замена ему.
--
-- Внешнего ключа на users нет намеренно: ошибку присылает и гость, у которого
-- аккаунта нет вовсе, а у вошедшего удаление аккаунта не должно уносить с
-- собой запись о поломке — она про сервис, а не про человека.
CREATE TABLE client_errors (
  id TEXT PRIMARY KEY,
  at INTEGER NOT NULL,
  -- NULL — гость. Знать, у одного человека беда или у всех, важнее всего.
  user_id TEXT,
  kind TEXT NOT NULL,
  message TEXT NOT NULL,
  stack TEXT,
  -- Экран, а не адрес: инвайт-код из пути вырезан на клиенте.
  page TEXT,
  agent TEXT,
  -- Хэш собранного бандла: без него не отличить «уже починили» от «не чинили».
  build TEXT,
  -- Отпечаток: по нему считается, сколько человек словили одно и то же.
  signature TEXT NOT NULL
);

-- Читают журнал всегда с конца: «что сломалось за последние сутки».
CREATE INDEX client_errors_at_idx ON client_errors (at DESC);
-- И вторым вопросом — «сколько раз это уже было».
CREATE INDEX client_errors_signature_idx ON client_errors (signature);
