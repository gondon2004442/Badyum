-- Юз: то, по чему человека находят и добавляют в контакты.
--
-- Раньше уникальность обеспечивала пара «ник + случайный тег»: «дюма» мог быть
-- не один, их разводило #4821. Теперь уникален сам юз, и человек выбирает его
-- сам. Тег исчез: он существовал только чтобы разводить одинаковые ники, а
-- четыре лишние цифры приходилось диктовать вслух ни за чем.
--
-- NULL означает «ещё не выбрал». Так и должно быть у всех, кто завёл аккаунт до
-- этого изменения: их кириллические ники в новые правила не переводятся, а
-- придумывать за человека то, по чему его будут звать, — не наше дело. При
-- следующем входе он выберет юз сам.
ALTER TABLE users ADD COLUMN username TEXT;

-- Уникальность по нижнему регистру, а не по строке как есть.
--
-- Регистр человек выбирает сам: «Dumax» пишется так, как он написал. Но занят
-- при этом и «dumax» — два юза, различающиеся только регистром, никто на слух
-- не различит, и это была бы подделка теми же средствами, от которых мы
-- закрылись, запретив кириллицу.
--
-- Несколько NULL уникальный индекс в SQLite допускает, поэтому «ещё не выбрал»
-- может быть у скольких угодно.
CREATE UNIQUE INDEX users_username_idx ON users (lower(username));
