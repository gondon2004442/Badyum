-- Пользователи.
--
-- Аккаунт не обязателен для звонка: гость по-прежнему заходит по ссылке, введя
-- одно имя. Запись здесь появляется только у тех, кто захотел постоянную
-- личность — ник#тег, друзей и узнаваемость между заходами.

CREATE TABLE users (
  id            TEXT    PRIMARY KEY,
  -- Ник и тег порознь: ник человек выбирает, тег выдаёт сервис, а вместе они
  -- уникальны. Так двое могут звать себя «дюма», не отбирая имя друг у друга.
  nick          TEXT    NOT NULL,
  tag           TEXT    NOT NULL,
  display_name  TEXT    NOT NULL,
  avatar_url    TEXT,
  -- Стабильный идентификатор пользователя у Google (claim `sub`). Именно он, а
  -- не почта: почту можно сменить, и тогда человек потерял бы свой аккаунт.
  google_sub    TEXT    NOT NULL UNIQUE,
  created_at    INTEGER NOT NULL,
  UNIQUE (nick, tag)
);

-- Поиск «кто такой дюма» идёт по нику, без учёта тега.
CREATE INDEX users_nick_idx ON users (nick);
